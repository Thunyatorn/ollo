def fixture_incident(client):
    incident = client.post('/api/demo/scenario', json={'scenario': 'distress'}).json()['incidents'][0]
    client.post(f"/api/incidents/{incident['id']}/acknowledge", json={'actor': 'Maya Chen'})
    client.post(f"/api/incidents/{incident['id']}/resolve", json={'actor': 'Maya Chen'})
    return incident


def test_plain_timeline_from_facts(client):
    incident = fixture_incident(client)
    report = client.get(f"/api/incidents/{incident['id']}/report").json()
    assert report['source'] == 'facts' and report['removed_lines'] == 0
    ids = [f['id'] for f in report['facts']]
    assert ids[0] == 'F1' and len(ids) == len(set(ids))
    md = report['markdown']
    assert incident['title'] in md and 'Maya Chen acknowledged the incident via dashboard' in md
    assert 'Airway status cannot be determined from video.' in md and md.rstrip().endswith('Generated by NestWatch from logged events.')
    assert all(not f['text'].startswith(('Primary caregiver ·', 'Backup caregiver ·')) for f in report['facts'])  # No duplicate call facts.
    assert client.get('/api/incidents/missing/report').status_code == 404


def test_claude_lines_must_cite_facts_and_avoid_diagnosis(client, monkeypatch):
    monkeypatch.setenv('ANTHROPIC_API_KEY', 'test-not-a-key')
    incident = fixture_incident(client)
    lines = [{'text': 'A possible distress alert opened in the toddler room.', 'facts': ['F1']},
             {'text': 'The child choked on food.', 'facts': ['F2']},
             {'text': 'Everything was fine.', 'facts': []},
             {'text': 'A teacher arrived.', 'facts': ['F99']},
             {'text': 'Maya Chen acknowledged it from the dashboard.', 'facts': ['F1', 'F3']}]
    fake = FakeClaude({'lines': lines})
    monkeypatch.setattr(api, 'claude_client', lambda: fake)
    report = client.get(f"/api/incidents/{incident['id']}/report").json()
    assert report['source'] == 'claude' and report['removed_lines'] == 3
    md = report['markdown']
    assert 'A possible distress alert opened in the toddler room. [F1]' in md and 'from the dashboard. [F1, F3]' in md
    assert 'choked' not in md and 'Everything was fine' not in md and 'teacher' not in md
    assert 'Airway status cannot be determined from video.' in md
    request = fake.calls[0]
    assert request['output_config']['format']['type'] == 'json_schema' and 'F1' in str(request['messages'])


def test_report_falls_back_when_no_line_survives(client, monkeypatch):
    monkeypatch.setenv('ANTHROPIC_API_KEY', 'test-not-a-key')
    incident = fixture_incident(client)
    monkeypatch.setattr(api, 'claude_client', lambda: FakeClaude({'lines': [{'text': 'Uncited.', 'facts': []}]}))
    report = client.get(f"/api/incidents/{incident['id']}/report").json()
    assert report['source'] == 'facts' and report['removed_lines'] == 1
    class Broken:
        messages = beta = None
    monkeypatch.setattr(api, 'claude_client', lambda: Broken())
    assert client.get(f"/api/incidents/{incident['id']}/report").json()['source'] == 'facts'
    assert client.get(f"/api/incidents/{incident['id']}/report?ai=false").json()['source'] == 'facts'
