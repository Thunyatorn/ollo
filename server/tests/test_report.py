OPINION = {'assessment': 'concern_visible', 'visibility': 'partial', 'observations': [{'frame_seq': 3, 'description': 'Person lying still on the floor.'}],
           'alternative_explanations': ['Lying down to play'], 'limitations': ['Injury cannot be determined from video.'], 'model': 'claude-haiku-5-5', 'cost_usd': 0.0003}


def test_events_are_linked_to_their_incident(tmp_path):
    store = Store(tmp_path / 'test.sqlite3')
    incident = store.observe('fall', ['Rapid drop to lying'], 'local_rule', 'high')
    store.annotate('fall', OPINION)
    store.transition(incident['id'], 'acknowledge', 'Maya Chen', channel='keypad')
    store.transition(incident['id'], 'resolve', 'Maya Chen')
    with store.db:
        store.event('session_reset', 'Unrelated session event')
    linked = {e['type'] for e in store.events() if e['incident_id'] == incident['id']}
    assert {'incident_opened', 'second_opinion', 'incident_acknowledged', 'incident_resolved'} <= linked
    assert next(e for e in store.events() if e['type'] == 'session_reset')['incident_id'] is None


